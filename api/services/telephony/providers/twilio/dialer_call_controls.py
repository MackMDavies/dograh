# ── Supabase (service role) ───────────────────────────────────────────────────────

def _headers() -> dict[str, str]:
    return {
        "apikey": SUPABASE_SERVICE_ROLE_KEY,
        "Authorization": f"Bearer {SUPABASE_SERVICE_ROLE_KEY}",
        "Content-Type": "application/json",
        "Prefer": "return=representation",
    }


async def _rest(method: str, path: str, *, params: dict | None = None, json: Any = None) -> Any:
    """One service-role PostgREST call. Returns parsed JSON, or None on any failure."""
    if not SUPABASE_URL or not SUPABASE_SERVICE_ROLE_KEY:
        return None
    try:
        async with httpx.AsyncClient(timeout=5.0) as client:
            response = await client.request(
                method, f"{SUPABASE_URL}{path}", params=params, json=json, headers=_headers(),
            )
            response.raise_for_status()
            return response.json() if response.content else None
    except Exception as exc:  # noqa: BLE001 - callers decide what "unknown" means
        logger.error(f"call-control: {method} {path} failed: {exc}")
        return None


async def _call_row(parent_call_sid: str) -> dict | None:
    rows = await _rest("GET", "/rest/v1/dialer_calls", params={
        "select": "id,parent_call_sid,child_call_sid,status,rep_user_id,provider,conference_sid,"
                  "lead_joined_at,ended_at,from_number,to_number,entry_id",
        "parent_call_sid": f"eq.{parent_call_sid}",
        "limit": "1",
    })
    if isinstance(rows, list) and rows and isinstance(rows[0], dict):
        return rows[0]
    return None


async def _events(parent_call_sid: str) -> list[dict]:
    rows = await _rest("GET", "/rest/v1/dialer_call_control_events", params={
        "select": "*",
        "parent_call_sid": f"eq.{parent_call_sid}",
        "order": "created_at.asc",
        "limit": "100",
    })
    return [r for r in rows if isinstance(r, dict)] if isinstance(rows, list) else []


async def _insert_event(row: dict) -> dict | None:
    rows = await _rest("POST", "/rest/v1/dialer_call_control_events", json=row)
    if isinstance(rows, list) and rows and isinstance(rows[0], dict):
        return rows[0]
    return None


async def _update_event(event_id: str, patch: dict) -> None:
    patch = {**patch, "updated_at": datetime.now(UTC).isoformat()}
    await _rest("PATCH", "/rest/v1/dialer_call_control_events",
                params={"id": f"eq.{event_id}"}, json=patch)


async def _rpc(name: str, body: dict) -> Any:
    return await _rest("POST", f"/rest/v1/rpc/{name}", json=body)


async def _offer_row(offer_id: str) -> dict | None:
    rows = await _rest("GET", "/rest/v1/inbound_calls", params={
        "select": "id,status,answered_by,rep_provider_call_id,ended_at",
        "provider_call_id": f"eq.{offer_id}",
        "limit": "1",
    })
    if isinstance(rows, list) and rows and isinstance(rows[0], dict):
        return rows[0]
    return None


async def _expire_offer(offer_id: str) -> bool:
    from api.services.telephony.dialer.inbound_call_log import expire_unanswered_inbound_call

    return await expire_unanswered_inbound_call(provider_call_id=offer_id, provider="twilio")


async def _number_block_reason(phone: str) -> str | None:
    """DNC/blocked numbers and the calling window, the same checks a dial gets."""
    from api.services.telephony.providers.twilio.dialer_call_log import (
        check_dialer_calling_hours,
        get_dialer_phone_block_reason,
    )

    blocked = await get_dialer_phone_block_reason(phone)
    if blocked:
        return blocked
    allowed, reason = await check_dialer_calling_hours(phone)
    if not allowed:
        return reason or "That number is outside its permitted calling hours."
    return None


async def _backend_endpoint() -> str:
    from api.utils.common import get_backend_endpoints

    try:
        backend, _ = await get_backend_endpoints()
    except Exception:  # noqa: BLE001
        return ""
    return str(backend or "").rstrip("/")


# ── Twilio ────────────────────────────────────────────────────────────────────────

async def _twilio():
    client = await _twilio_client()
    if client is None:
        raise HTTPException(status_code=503, detail="The dialer's Twilio account is not configured.")
    return client


async def _conference_sid(client, row: dict) -> str | None:
    sid = row.get("conference_sid")
    if isinstance(sid, str) and sid.startswith("CF"):
        return sid
    try:
        found = await asyncio.to_thread(
            client.conferences.list,
            friendly_name=conference_name_for(row["parent_call_sid"]),
            status="in-progress",
            limit=1,
        )
    except Exception as exc:  # noqa: BLE001
        logger.warning(f"call-control: conference lookup failed: {exc}")
        return None
    return found[0].sid if found else None


async def _participants(client, conference_sid: str) -> list[Any]:
    try:
        items = await asyncio.to_thread(client.conferences(conference_sid).participants.list)
    except Exception as exc:  # noqa: BLE001
        logger.warning(f"call-control: participant list failed: {exc}")
        return []
    return [p for p in items if str(getattr(p, "status", "connected")) in _LIVE_PARTICIPANT]


async def _update_participant(client, conference_sid: str, call_sid: str, **params) -> bool:
    try:
        await asyncio.to_thread(client.conferences(conference_sid).participants(call_sid).update, **params)
        return True
    except Exception as exc:  # noqa: BLE001
        logger.error(f"call-control: participant {call_sid} update {sorted(params)} failed: {exc}")
        return False


async def _remove_participant(client, conference_sid: str, call_sid: str) -> bool:
    try:
        await asyncio.to_thread(client.conferences(conference_sid).participants(call_sid).delete)
        return True
    except Exception as exc:  # noqa: BLE001
        logger.error(f"call-control: participant {call_sid} removal failed: {exc}")
        return False


async def _recording(client, conference_sid: str | None) -> tuple[str, Any]:
    """The conference recording's state, truthfully: absent is not paused."""
    if not conference_sid:
        return "absent", None
    try:
        recordings = await asyncio.to_thread(client.conferences(conference_sid).recordings.list, limit=5)
    except Exception as exc:  # noqa: BLE001
        logger.warning(f"call-control: recording lookup failed: {exc}")
        return "unknown", None
    for rec in recordings:
        status = str(getattr(rec, "status", ""))
        if status in {"in-progress", "paused"}:
            return status, rec
    if recordings:
        return "stopped", None
    return "absent", None


# ── Authorisation ─────────────────────────────────────────────────────────────────

def _rep_id(user) -> str:
    rep_user_id = getattr(user, "provider_id", None)
    if not isinstance(rep_user_id, str) or not rep_user_id:
        raise HTTPException(status_code=503, detail="Your account is missing its dialer user mapping.")
    return rep_user_id


async def _own_call(parent_call_sid: str, user) -> dict:
    """This rep's own call row, or 404 with the same sentence for every refusal."""
    rep_user_id = _rep_id(user)
    if not re.fullmatch(r"[A-Za-z0-9_.:-]{1,64}", parent_call_sid or ""):
        raise HTTPException(status_code=404, detail="This active call was not found for your account.")
    row = await _call_row(parent_call_sid)
    if not row or str(row.get("rep_user_id") or "") != rep_user_id:
        raise HTTPException(status_code=404, detail="This active call was not found for your account.")
    return row


async def _own_live_twilio_call(parent_call_sid: str, user) -> dict:
    row = await _own_call(parent_call_sid, user)
    if row.get("provider") != "twilio":
        raise HTTPException(status_code=409, detail=_unsupported_reason(row.get("provider")))
    if not CALL_SID.fullmatch(parent_call_sid):
        raise HTTPException(status_code=404, detail="This active call was not found for your account.")
    if row.get("ended_at") or row.get("status") in {"completed", "busy", "failed", "no-answer", "canceled"}:
        raise HTTPException(status_code=409, detail="The call has already ended.")
    return row


def _unsupported_reason(provider: Any) -> str:
    name = {"signalwire": "SignalWire", "telnyx": "Telnyx", "vonage": "Vonage"}.get(str(provider or ""), "this provider")
    return f"Hold, recording, keypad tones, transfer and add call run through Twilio. They are not available on {name} calls yet."


# ── State ─────────────────────────────────────────────────────────────────────────

_CAPS = ("hold", "record", "dtmf", "transfer", "transfer_agent", "add_call")
_AGENT_REASON = "Transfer to an AI agent is only available for parallel-dial second pickups today."


def _unsupported_state(provider: Any, reason: str | None = None) -> dict:
    why = reason or _unsupported_reason(provider)
    return {
        "provider": str(provider or "unknown"),
        "on_hold": False,
        "recording": "unknown",
        "consent_played": False,
        "participants": [],
        "transfer": None,
        "max_participants": MAX_PARTICIPANTS,
        "capabilities": {c: False for c in _CAPS},
        "reasons": {c: (_AGENT_REASON if c == "transfer_agent" and not reason else why) for c in _CAPS},
    }


def _pending_targets(events: list[dict]) -> list[dict]:
    return [e for e in events if e.get("action") in {"transfer", "add_call"} and e.get("status") in _PENDING_EVENT]


async def _state(client, row: dict, events: list[dict] | None = None) -> dict:
    parent = row["parent_call_sid"]
    child = row.get("child_call_sid")
    if events is None:
        events = await _events(parent)
    conference_sid = await _conference_sid(client, row)
    live = await _participants(client, conference_sid) if conference_sid else []
    recording, _ = await _recording(client, conference_sid)

    by_sid = {e.get("participant_call_sid"): e for e in events if e.get("participant_call_sid")}
    participants: list[dict] = []
    prospect = None
    seen: set[str] = set()
    for p in live:
        sid = str(getattr(p, "call_sid", ""))
        seen.add(sid)
        status = "on_hold" if getattr(p, "hold", False) else (
            "connected" if str(getattr(p, "status", "connected")) == "connected" else "connecting")
        if sid == parent:
            kind, label = "rep", "You"
        elif sid == child:
            kind, label, prospect = "prospect", "Prospect", p
        elif sid in by_sid:
            kind = by_sid[sid].get("target_kind") or "number"
            label = by_sid[sid].get("target_label") or "Participant"
        else:
            kind, label = "number", "Participant"
        participants.append({"id": sid, "kind": kind, "label": label, "status": status})
    for event in _pending_targets(events):
        if event.get("participant_call_sid") in seen:
            continue
        participants.append({
            "id": str(event["id"]),
            "kind": event.get("target_kind") or "number",
            "label": event.get("target_label") or "Participant",
            "status": "connecting",
        })

    transfer = None
    for event in reversed(events):
        if event.get("action") == "transfer":
            status = event.get("status")
            transfer = {
                "mode": event.get("mode"),
                "target_label": event.get("target_label"),
                "status": "connecting" if status == "connecting" else
                          "connected" if status == "connected" else
                          "completed" if status in {"completed", "left"} else
                          "cancelled" if status == "cancelled" else "failed",
            }
            break

    reasons: dict[str, str] = {}
    prospect_here = prospect is not None
    count = len([p for p in participants if p["status"] != "left"])
    transfer_pending = bool(transfer and transfer["status"] in {"connecting", "connected"})
    caps = {
        "hold": prospect_here,
        "dtmf": prospect_here,
        "record": recording in {"in-progress", "paused"},
        "transfer": prospect_here and not transfer_pending and count < MAX_PARTICIPANTS,
        "transfer_agent": False,
        "add_call": prospect_here and count < MAX_PARTICIPANTS,
    }
    waiting = "Available once they answer and join the call."
    if not prospect_here:
        for c in ("hold", "dtmf", "transfer", "add_call"):
            reasons[c] = waiting
    elif count >= MAX_PARTICIPANTS:
        reasons["transfer"] = reasons["add_call"] = f"A call can have at most {MAX_PARTICIPANTS} people on it."
    if transfer_pending:
        reasons["transfer"] = "A transfer is already in progress."
    if not caps["record"]:
        reasons["record"] = (
            "The recording status could not be read from Twilio." if recording == "unknown"
            else "No recording is running on this call."
        )
    reasons["transfer_agent"] = _AGENT_REASON

    return {
        "provider": "twilio",
        "on_hold": bool(prospect is not None and getattr(prospect, "hold", False)),
        "recording": recording,
        # The disclosure <Say> runs on the prospect's leg BEFORE it joins the conference,
        # and lead_joined_at is stamped from that join. No join, no claim.
        "consent_played": bool(row.get("lead_joined_at")),
        "participants": participants,
        "transfer": transfer,
        "max_participants": MAX_PARTICIPANTS,
        "capabilities": caps,
        "reasons": reasons,
    }


async def _require_conference(client, row: dict) -> str:
    sid = await _conference_sid(client, row)
    if not sid:
        raise HTTPException(status_code=409, detail="The call is not connected yet.")
    return sid


def _require_prospect(row: dict, live: list[Any]) -> str:
    child = row.get("child_call_sid")
    if not isinstance(child, str) or not CALL_SID.fullmatch(child) or not any(
        str(getattr(p, "call_sid", "")) == child for p in live
    ):
        raise HTTPException(status_code=409, detail="They have not joined the call yet.")
    return child


