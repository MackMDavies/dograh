"""In-call controls for a rep's own Twilio dialer call.

Every Twilio dialer call is a named Conference ("call-{parent_call_sid}", see
dialer_conference.py): the rep's browser leg (CallSid = parent_call_sid, joined with
endConferenceOnExit=true) and the prospect's PSTN leg (child_call_sid, joined through
dialer-conference-join, which plays the recording disclosure first). That shape is what
makes these controls possible at all - a bridged two-party <Dial> has no handle for
holding one side or adding a third.

  hold / unhold    Participant update hold=True/False on the PROSPECT participant.
                   The rep stays in the conference; the call and its timer continue.
  record pause /   The conference's own recording resource, status paused / in-progress.
  resume
  dtmf             Participant announce_url on the prospect -> TwiML <Play digits>, so
                   the tones are generated by Twilio on the prospect's leg (an IVR hears
                   them), not mixed through the conference from the browser.
  transfer         Teammate: an inbound_calls invitation the teammate's browser accepts
  add call         (same mechanism as parallel overflow). Number: a Conference
                   Participant create to the E.164 number from the call's caller ID.
                   Cold = prospect held until the target connects, then the rep leaves.
                   Warm = target joins, rep completes (leaves) or cancels (target drops).

Authorisation is the manual-voicemail-drop rule: a sales dialer role, and the
dialer_calls row for this parent_call_sid must be this rep's own Twilio call. The
browser never sees credentials or any SID other than its own.

Everything carrier-facing fails soft into an HTTPException with a sentence a rep can
read; nothing here may raise into the call itself.
"""

