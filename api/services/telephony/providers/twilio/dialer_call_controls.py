@router.get("/dialer/call-control/{parent_call_sid}")
async def call_control_state(parent_call_sid: str, user=Depends(require_sales_dialer_role)):
    row = await _own_call(parent_call_sid, user)
    if row.get("provider") != "twilio":
        return _unsupported_state(row.get("provider"))
    if row.get("ended_at"):
        return _unsupported_state("twilio", "The call has ended.")
    client = await _twilio_client()
    if client is None:
        return _unsupported_state("twilio", "The dialer's Twilio account is not configured.")
    return await _state(client, row)


@router.post("/dialer/call-control")
async def call_control_action(
    body: CallControlRequest, request: Request, user=Depends(require_sales_dialer_role),
):
    row = await _own_live_twilio_call(body.parent_call_sid, user)
    rep_user_id = _rep_id(user)
    client = await _twilio()
    conference_sid = await _require_conference(client, row)

    if body.action in {"hold", "unhold", "dtmf"}:
        live = await _participants(client, conference_sid)
        child = _require_prospect(row, live)
        if body.action == "dtmf":
            digits = (body.digits or "").strip()
            if not DTMF.fullmatch(digits):
                raise HTTPException(status_code=400, detail="Keypad tones must be 0-9, * or #.")
            endpoint = await _backend_endpoint()
            if not endpoint.startswith("https://"):
                raise HTTPException(status_code=503, detail="Keypad tones need the secure callback endpoint, which is unavailable.")
            announce = f"{endpoint}/api/v1/telephony/dialer/call-control/dtmf-twiml?" + urlencode({"digits": digits})
            ok = await _update_participant(client, conference_sid, child,
                                           announce_url=announce, announce_method="POST")
        else:
            hold = body.action == "hold"
            params: dict[str, Any] = {"hold": hold}
            if hold:
                params.update(hold_url=HOLD_URL, hold_method="GET")
            ok = await _update_participant(client, conference_sid, child, **params)
        if not ok:
            raise HTTPException(status_code=502, detail="Twilio refused that change. The call was left as it was.")
    else:
        status, recording = await _recording(client, conference_sid)
        if recording is None:
            raise HTTPException(status_code=409, detail="No recording is running on this call.")
        target = "paused" if body.action == "record_pause" else "in-progress"
        if status != target:
            try:
                params = {"status": target}
                if target == "paused":
                    params["pause_behavior"] = "skip"
                await asyncio.to_thread(
                    client.conferences(conference_sid).recordings(recording.sid).update, **params,
                )
            except Exception as exc:  # noqa: BLE001
                logger.error(f"call-control: recording {body.action} failed: {exc}")
                raise HTTPException(status_code=502, detail="Twilio refused to change the recording.")

    await _insert_event({
        "parent_call_sid": body.parent_call_sid, "rep_user_id": rep_user_id,
        "action": body.action, "status": "done",
        "detail": f"{len(body.digits or '')} digits" if body.action == "dtmf" else None,
    })
    return await _state(client, row)


@router.post("/dialer/call-control/dtmf-twiml", include_in_schema=False)
async def dtmf_twiml(request: Request):
    """The announce TwiML that plays keypad tones on the prospect's leg."""
    from api.services.telephony.providers.twilio.routes import _verify_twilio_signature

    form_data = dict(await request.form())
    empty = '<?xml version="1.0" encoding="UTF-8"?><Response/>'
    if not await _verify_twilio_signature(request, form_data):
        return HTMLResponse(content=empty, media_type="application/xml")
    digits = str(request.query_params.get("digits") or "")
    if not DTMF.fullmatch(digits):
        return HTMLResponse(content=empty, media_type="application/xml")
    return HTMLResponse(
        content=f'<?xml version="1.0" encoding="UTF-8"?><Response><Play digits={quoteattr(digits)}/></Response>',
        media_type="application/xml",
    )


async def _add_target(
    client, row: dict, rep_user_id: str, target, *, action: str, mode: str | None,
    conference_sid: str, live: list[Any], hold_prospect: bool,
) -> dict:
    """Invite a teammate or dial a number into this conference. Returns the event row."""
    events = await _events(row["parent_call_sid"])
    count = len(live) + len([e for e in _pending_targets(events)
                             if e.get("participant_call_sid") not in {str(getattr(p, "call_sid", "")) for p in live}])
    if count >= MAX_PARTICIPANTS:
        raise HTTPException(status_code=409, detail=f"A call can have at most {MAX_PARTICIPANTS} people on it.")
    if action == "transfer" and any(e.get("action") == "transfer" for e in _pending_targets(events)):
        raise HTTPException(status_code=409, detail="A transfer is already in progress.")
    child = _require_prospect(row, live)

    event: dict[str, Any] = {
        "parent_call_sid": row["parent_call_sid"], "rep_user_id": rep_user_id,
        "action": action, "mode": mode, "status": "connecting",
    }
    if isinstance(target, TeammateTarget):
        offer_id = f"xfer-{uuid.uuid4()}"
        result = await _rpc("dialer_call_control_offer_teammate", {
            "p_parent_call_sid": row["parent_call_sid"], "p_rep_user_id": rep_user_id,
            "p_target_user_id": str(target.user_id), "p_offer_id": offer_id,
        })
        first = result[0] if isinstance(result, list) and result else None
        if not isinstance(first, dict) or not first.get("inbound_call_id"):
            reason = (first or {}).get("reason") if isinstance(first, dict) else None
            raise HTTPException(status_code=409, detail={
                "unavailable": "That teammate is not available to take a call right now.",
                "busy": "That teammate is already being rung for another call.",
                "not_teammate": "You can only transfer to teammates on your own dialer account.",
                "call_not_found": "The call has already ended.",
            }.get(reason or "", "That teammate could not be invited. Try again."))
        event.update(target_kind="teammate", target_user_id=str(target.user_id),
                     target_label=first.get("target_name") or "Teammate", offer_call_id=offer_id)
    else:
        phone = target.phone.strip()
        if not E164.fullmatch(phone):
            raise HTTPException(status_code=400, detail="Enter the number in international format, like +15551234567.")
        if phone in {row.get("to_number"), row.get("from_number")}:
            raise HTTPException(status_code=409, detail="That number is already on this call.")
        blocked = await _number_block_reason(phone)
        if blocked:
            raise HTTPException(status_code=409, detail=blocked)
        caller_id = row.get("from_number")
        if not isinstance(caller_id, str) or not E164.fullmatch(caller_id):
            raise HTTPException(status_code=409, detail="This call has no caller ID to dial out from.")
        try:
            created = await asyncio.to_thread(
                client.conferences(conference_sid).participants.create,
                from_=caller_id, to=phone, early_media=True, beep="false",
                end_conference_on_exit=False, timeout=TARGET_CONNECT_SECONDS,
            )
        except Exception as exc:  # noqa: BLE001
            logger.error(f"call-control: could not dial {action} participant: {exc}")
            raise HTTPException(status_code=502, detail="Twilio could not place that call. Nothing changed on yours.")
        event.update(target_kind="number", target_phone=phone, target_label=phone,
                     participant_call_sid=str(getattr(created, "call_sid", "") or "") or None)

    if hold_prospect:
        if await _update_participant(client, conference_sid, child, hold=True, hold_url=HOLD_URL, hold_method="GET"):
            event["held_prospect"] = True
    saved = await _insert_event(event)
    if not saved:
        # The target is already being rung; without a ledger row the watcher cannot
        # follow it, so withdraw it rather than leave an untracked party on the line.
        await _withdraw(client, conference_sid, event)
        if event.get("held_prospect"):
            await _update_participant(client, conference_sid, child, hold=False)
        raise HTTPException(status_code=503, detail="The transfer could not be recorded, so it was withdrawn.")
    _spawn(_watch_target(saved["id"], row, conference_sid))
    return saved


async def _withdraw(client, conference_sid: str, event: dict) -> None:
    if event.get("offer_call_id"):
        await _expire_offer(str(event["offer_call_id"]))
    sid = event.get("participant_call_sid")
    if sid:
        await _remove_participant(client, conference_sid, str(sid))


async def _rep_leaves(client, conference_sid: str, row: dict, target_sid: str | None) -> bool:
    """Hand the conference over: the target now ends it on exit, the rep goes."""
    child = row.get("child_call_sid")
    if target_sid:
        await _update_participant(client, conference_sid, target_sid, end_conference_on_exit=True)
    if isinstance(child, str) and CALL_SID.fullmatch(child):
        await _update_participant(client, conference_sid, child, hold=False)
    # Order matters: without this the rep's exit would end the conference for everyone.
    if not await _update_participant(client, conference_sid, row["parent_call_sid"], end_conference_on_exit=False):
        return False
    return await _remove_participant(client, conference_sid, row["parent_call_sid"])


async def _target_sid(client, conference_sid: str, event: dict) -> str | None:
    """The target's Twilio CallSid once it is actually connected in the conference."""
    sid = event.get("participant_call_sid")
    if not sid and event.get("offer_call_id"):
        offer = await _offer_row(str(event["offer_call_id"]))
        rep_leg = (offer or {}).get("rep_provider_call_id")
        if (offer or {}).get("status") == "answered" and isinstance(rep_leg, str) and CALL_SID.fullmatch(rep_leg):
            sid = rep_leg
    if not sid:
        return None
    for p in await _participants(client, conference_sid):
        if str(getattr(p, "call_sid", "")) == sid and str(getattr(p, "status", "")) == "connected":
            return str(sid)
    return None


async def _watch_target(event_id: str, row: dict, conference_sid: str) -> None:
    """Follow one transfer/add-call target until it connects or is withdrawn.

    Runs server-side so a rep closing the tab cannot strand a held prospect. On
    connect: the target stops ending the conference on exit (so an added party or a
    consulting teammate leaving does not hang up the prospect); a cold transfer then
    hands the call over. On timeout: the target is withdrawn and a hold this transfer
    placed is lifted.
    """
    client = await _twilio_client()
    if client is None:
        return
    loops = max(1, int(TARGET_CONNECT_SECONDS / max(WATCH_INTERVAL_SECONDS, 0.1)))
    for _ in range(loops):
        events = await _events(row["parent_call_sid"])
        event = next((e for e in events if str(e.get("id")) == str(event_id)), None)
        if not event or event.get("status") != "connecting":
            return
        sid = await _target_sid(client, conference_sid, event)
        if sid:
            await _update_participant(client, conference_sid, sid, end_conference_on_exit=False)
            await _update_event(event_id, {"status": "connected", "participant_call_sid": sid})
            if event.get("action") == "transfer" and event.get("mode") == "cold":
                left = await _rep_leaves(client, conference_sid, row, sid)
                await _update_event(event_id, {"status": "completed" if left else "failed",
                                               "detail": None if left else "Rep leg could not be released"})
            return
        await asyncio.sleep(WATCH_INTERVAL_SECONDS)
    await _withdraw(client, conference_sid, event or {})
    if (event or {}).get("held_prospect") and row.get("child_call_sid"):
        await _update_participant(client, conference_sid, str(row["child_call_sid"]), hold=False)
    await _update_event(event_id, {"status": "failed", "detail": "Target did not connect in time"})


_background: set[asyncio.Task] = set()


def _spawn(coro) -> None:
    try:
        task = asyncio.create_task(coro)
    except RuntimeError:
        coro.close()
        return
    _background.add(task)
    task.add_done_callback(_background.discard)


