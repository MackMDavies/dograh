@router.delete("/dialer/call-control/participants/{participant_id}")
async def call_control_remove_participant(
    participant_id: str, parent_call_sid: str, user=Depends(require_sales_dialer_role),
):
    row = await _own_live_twilio_call(parent_call_sid, user)
    client = await _twilio()
    conference_sid = await _require_conference(client, row)
    if participant_id in {row.get("parent_call_sid"), row.get("child_call_sid")}:
        raise HTTPException(status_code=409, detail="Use End call to leave, or end the call to drop the prospect.")
    events = await _events(parent_call_sid)
    event = None
    if EVENT_ID.fullmatch(participant_id):
        event = next((e for e in events if str(e.get("id")) == participant_id), None)
    elif CALL_SID.fullmatch(participant_id):
        event = next((e for e in events if e.get("participant_call_sid") == participant_id), None)
    if not event or event.get("action") not in {"transfer", "add_call"}:
        raise HTTPException(status_code=404, detail="That person is not on this call.")
    await _update_event(str(event["id"]), {"status": "left" if event.get("status") == "connected" else "cancelled"})
    await _withdraw(client, conference_sid, event)
    if CALL_SID.fullmatch(participant_id):
        await _remove_participant(client, conference_sid, participant_id)
    await _insert_event({"parent_call_sid": parent_call_sid, "rep_user_id": _rep_id(user),
                         "action": "remove_participant", "status": "done",
                         "target_label": event.get("target_label")})
    return await _state(client, row)
